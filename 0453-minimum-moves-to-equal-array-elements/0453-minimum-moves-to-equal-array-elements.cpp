class Solution {
public:
    int minMoves(vector<int>& nums) {

        // 2, 3, 6, 3 (gaps from max: 4, 3, 0, 3) (gaps from min: 0, 1, 4, 1)

        // 3, 4, 6, 4
        // 4, 5, 6, 5
        // 5, 6, 6, 6
        // 6, 7, 6, 7
        // 7, 8, 7, 7
        // 8, 8, 8, 8

        // 1, 2, 3, 4 (gaps from max: 3, 2, 1, 0) (gaps from min: 0, 1, 2, 3)

        // 2, 3, 4, 4
        // 3, 4, 5, 4
        // 4, 5, 5, 5
        // 5, 6, 6, 5
        // 6, 6, 7, 6
        // 7, 7, 7, 7

        // 2, 3, 6, 4

        // 3, 4, 6, 5, 8
        // 4, 5, 7, 6, 8
        // 5, 6, 8, 7, 8
        // 6, 7, 9, 8, 8
        // 7, 8, 9, 8, 8    
        // 8, 9, 9, 9, 9 ----> after this point (n-1) steps
        // 9, 10, 10, 10, 9
        // 10, 11, 11, 10, 10
        // 11, 11, 12, 11, 11
        // 12, 12, 12, 12, 12

        // 1, 2, 3, 4, 5, 6

        // 2, 3, 4, 5, 6, 6
        // 3, 4, 5, 6, 7, 6
        // 4, 5, 6, 7, 7, 7
        // 5, 6, 7, 7, 8, 8
        // 6, 7, 8, 8, 8, 9
        // 7, 8, 9, 9, 9, 9
        // 8, 9, 9, 10, 10, 10
        // 9, 10, 10, 10, 11, 11
        // 10, 10, 11, 11, 12, 12
        // 11, 11, 11, 12, 13, 13
        // 12, 12, 12, 12, 14, 14
        // 13, 13, 13, 13, 14, 15
        // 14, 14, 14, 14, 14, 16
        // 15, 15, 15, 15, 15, 16
        // 16, 16, 16, 16, 16, 16


        int minNums = nums[0], n = nums.size();
        for(int i=1; i<n; i++){
            if(nums[i] < minNums) minNums = nums[i];
        }

        int gapsFromMinSum = 0;
        for(int i=0; i<n; i++){
            gapsFromMinSum += nums[i] - minNums;
        }
        return gapsFromMinSum;
    }
};